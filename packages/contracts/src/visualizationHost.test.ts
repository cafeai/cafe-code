import { randomUUID } from "node:crypto";
import * as Result from "effect/Result";
import * as Schema from "effect/Schema";
import { describe, expect, it } from "vitest";
import {
  VisualizationHostConnection,
  VisualizationHostDocument,
  VisualizationHostOpenInput,
  VisualizationHostPresentation,
  VisualizationHostPrepareInput,
  VisualizationHostPreviewInput,
  VisualizationHostUpdateInput,
  VisualizationHostCapabilities,
  VisualizationHostCapacity,
  VisualizationHostEvent,
  VisualizationHostDiscardInput,
  VisualizationHostState,
  VisualizationHostInspection,
  VisualizationHostYieldResult,
} from "./visualizationHost.ts";

describe("private visualization native host schemas", () => {
  it("admits only exact finite layout metadata on the layout event variant", () => {
    const decode = Schema.decodeUnknownResult(VisualizationHostEvent);
    const value = {
      leaseId: randomUUID(),
      openingTicket: "a".repeat(64),
      state: "layout",
      layout: { height: 420, constrained: false, sequence: 1 },
    };
    expect(Result.isSuccess(decode(value))).toBe(true);
    for (const layout of [
      { ...value.layout, height: NaN },
      { ...value.layout, height: 79 },
      { ...value.layout, height: 2001 },
      { ...value.layout, height: 420.5 },
      { ...value.layout, sequence: 0 },
      { ...value.layout, sequence: Infinity },
      { ...value.layout, source: "private" },
      { ...value.layout, constrained: "true" },
    ])
      expect(Result.isFailure(decode({ ...value, layout }))).toBe(true);
    expect(Result.isFailure(decode({ ...value, state: "active" }))).toBe(true);
    expect(Result.isFailure(decode({ ...value, layout: undefined }))).toBe(true);
  });
  it("distinguishes old manual hosts from exact finite automatic pool capabilities", () => {
    const decode = Schema.decodeUnknownResult(VisualizationHostCapabilities);
    const legacy = { available: true, reason: "ready", maxActive: 1, activeLeaseMs: 300_000 };
    const pool = {
      ...legacy,
      poolVersion: 1,
      autoGenerated: true,
      maxActive: 4,
      maxMcpApps: 1,
      maxPreviews: 1,
    };
    expect(Result.isSuccess(decode(legacy))).toBe(true);
    expect(Result.isSuccess(decode(pool))).toBe(true);
    expect(Result.isSuccess(decode({ ...pool, generatedLifecycle: "visible" }))).toBe(true);
    expect(Result.isFailure(decode({ ...pool, generatedLifecycle: "unlimited" }))).toBe(true);
    for (const value of [
      { ...legacy, autoGenerated: true },
      { ...pool, maxActive: 5 },
      { ...pool, maxMcpApps: 2 },
      { ...pool, poolVersion: 2 },
    ])
      expect(Result.isFailure(decode(value))).toBe(true);
    const capacity = Schema.decodeUnknownResult(VisualizationHostCapacity);
    const state = {
      poolVersion: 1,
      sequence: 0,
      available: true,
      viewerCount: 4,
      freeViewers: 0,
      preparedCount: 4,
      freePreparations: 0,
      mcpAppAvailable: false,
      previewBusy: true,
    };
    expect(Result.isSuccess(capacity(state))).toBe(true);
    for (const patch of [
      { viewerCount: 5 },
      { sequence: Infinity },
      { freePreparations: -1 },
      { source: "private" },
    ])
      expect(Result.isFailure(capacity({ ...state, ...patch }))).toBe(true);
  });
  it("admits explicit nullable generated lifetime without infinity or timestamp sentinels", () => {
    const leaseId = randomUUID();
    for (const expiresAtMs of [null, 300000]) {
      expect(
        Result.isSuccess(
          Schema.decodeUnknownResult(VisualizationHostState)({
            leaseId,
            state: "active",
            expiresAtMs,
          }),
        ),
      ).toBe(true);
      expect(
        Result.isSuccess(
          Schema.decodeUnknownResult(VisualizationHostInspection)({
            leaseId,
            documentGeneration: randomUUID(),
            state: "active",
            expiresAtMs,
          }),
        ),
      ).toBe(true);
      expect(
        Result.isSuccess(
          Schema.decodeUnknownResult(VisualizationHostYieldResult)({
            leaseId,
            state: "retired",
            expiresAtMs,
          }),
        ),
      ).toBe(true);
    }
    for (const expiresAtMs of [Infinity, NaN, -1, "null", undefined])
      expect(
        Result.isFailure(
          Schema.decodeUnknownResult(VisualizationHostState)({
            leaseId,
            state: "active",
            expiresAtMs,
          }),
        ),
      ).toBe(true);
  });
  it("binds early events to exact consumed ticket and admits only finite wheel metadata", () => {
    const decode = Schema.decodeUnknownResult(VisualizationHostEvent);
    const value = {
      leaseId: randomUUID(),
      openingTicket: "a".repeat(64),
      state: "wheel",
      wheel: { deltaX: 0, deltaY: 60 },
    };
    expect(Result.isSuccess(decode(value))).toBe(true);
    for (const patch of [
      { openingTicket: "wrong" },
      { wheel: { deltaX: 0, deltaY: NaN } },
      { wheel: { deltaX: 0, deltaY: 2049 } },
      { wheel: undefined },
      { state: "active" },
      { json: "private" },
    ])
      expect(Result.isFailure(decode({ ...value, ...patch }))).toBe(true);
    const discard = Schema.decodeUnknownResult(VisualizationHostDiscardInput);
    expect(Result.isSuccess(discard({ ticket: "a".repeat(64) }))).toBe(true);
    expect(Result.isFailure(discard({ ticket: "a".repeat(64), owner: "arbitrary" }))).toBe(true);
  });
  it("keeps the finite full CSS viewport separate from an optional strict visible subset", () => {
    const bounds = { x: 20, y: -100, width: 400, height: 600 };
    const value = { ticket: "a".repeat(64), bounds, appearance: "light" };
    const decode = Schema.decodeUnknownResult(VisualizationHostOpenInput);
    const clipBounds = { x: 20, y: 80, width: 300, height: 200 };
    expect(Result.isSuccess(decode({ ...value, clipBounds }))).toBe(true);
    expect(Result.isSuccess(decode(value))).toBe(true);
    for (const clip of [
      { ...clipBounds, x: 19 },
      { ...clipBounds, width: 401 },
      { ...clipBounds, height: 421 },
      { ...clipBounds, width: NaN },
      { ...clipBounds, nativeZoom: 1.3 },
    ])
      expect(Result.isFailure(decode({ ...value, clipBounds: clip }))).toBe(true);
    const update = Schema.decodeUnknownResult(VisualizationHostUpdateInput);
    expect(
      Result.isSuccess(
        update({ leaseId: randomUUID(), bounds, clipBounds, visible: true, appearance: "light" }),
      ),
    ).toBe(true);
    expect(
      Result.isFailure(
        update({
          leaseId: randomUUID(),
          bounds,
          clipBounds: { ...clipBounds, x: 19 },
          visible: true,
          appearance: "light",
        }),
      ),
    ).toBe(true);
  });
  it("admits only exact loopback discovery with opaque generation and bearer", () => {
    const decode = Schema.decodeUnknownResult(VisualizationHostConnection);
    const value = {
      version: 1,
      generation: randomUUID(),
      token: "a".repeat(64),
      url: "http://127.0.0.1:1234/visualizations",
    };
    expect(Result.isSuccess(decode(value))).toBe(true);
    for (const url of [
      "https://127.0.0.1:1234/visualizations",
      "http://localhost:1234/visualizations",
      "http://127.0.0.1:1234/visualizations?secret=1",
      "http://127.0.0.1:1234/other",
    ])
      expect(Result.isFailure(decode({ ...value, url }))).toBe(true);
    expect(Result.isFailure(decode({ ...value, source: "private" }))).toBe(true);
  });
  it("keeps source private and uses the same admitted viewport range", () => {
    const decode = Schema.decodeUnknownResult(VisualizationHostDocument);
    const document = {
      kind: "generated",
      html: "<p>日本語 🐈</p>",
      assets: [],
      width: 1600,
      height: 2000,
      appearance: "dark",
    };
    expect(Result.isSuccess(decode(document))).toBe(true);
    expect(Result.isSuccess(decode({ ...document, height: 80 }))).toBe(true);
    for (const patch of [
      { html: "日".repeat((512 * 1024) / 3 + 1) },
      { height: 2001 },
      {
        assets: Array.from({ length: 17 }, () => ({
          id: "image",
          mime: "image/png",
          base64: "AAAA",
        })),
      },
      { html: "\ud800" },
      { path: "/secret" },
    ])
      expect(Result.isFailure(decode({ ...document, ...patch }))).toBe(true);
  });
  it("accepts no renderer source, URL or native path selector", () => {
    const value = {
      ticket: "a".repeat(64),
      bounds: { x: 0, y: 0, width: 400, height: 200 },
      appearance: "light",
    };
    const decode = Schema.decodeUnknownResult(VisualizationHostOpenInput);
    expect(Result.isSuccess(decode(value))).toBe(true);
    for (const field of ["html", "url", "path", "owner", "documentGeneration"])
      expect(Result.isFailure(decode({ ...value, [field]: "private" }))).toBe(true);
    expect(
      Result.isFailure(decode({ ...value, bounds: { ...value.bounds, width: Infinity } })),
    ).toBe(true);
    expect(
      Result.isFailure(
        Schema.decodeUnknownResult(VisualizationHostPrepareInput)({ ...value, document: "wrong" }),
      ),
    ).toBe(true);
  });
  it("admits finite color-only presentation and refuses executable CSS", () => {
    const color = "#123456";
    const colors = {
      background: color,
      foreground: color,
      muted: color,
      accent: color,
      accentForeground: color,
      chart1: color,
      chart2: color,
      chart3: color,
      chart4: color,
      chart5: color,
      chart6: color,
    };
    const value = { locale: "en", reducedMotion: true, scale: 1, colors };
    const decode = Schema.decodeUnknownResult(VisualizationHostPresentation);
    expect(Result.isSuccess(decode(value))).toBe(true);
    for (const accent of [
      "url(file:///secret)",
      "red;display:none",
      "var(--secret)",
      "expression(alert(1))",
    ])
      expect(Result.isFailure(decode({ ...value, colors: { ...colors, accent } }))).toBe(true);
    expect(Result.isFailure(decode({ ...value, scale: NaN }))).toBe(true);
    expect(Result.isFailure(decode({ ...value, provider: "secret" }))).toBe(true);
  });
  it("admits bounded original replay only for a private App preview", () => {
    const owner = { environmentId: "fixture", threadId: "fixture", operationId: randomUUID() };
    const document = {
      kind: "mcp-app",
      html: "<p>private</p>",
      assets: [],
      width: 400,
      height: 200,
      appearance: "light",
    };
    const previewReplay = {
      originalInputJson: '{"private":"input"}',
      originalResultJson: '{"content":[]}',
    };
    const decode = Schema.decodeUnknownResult(VisualizationHostPreviewInput);
    expect(Result.isSuccess(decode({ owner, document, previewReplay }))).toBe(true);
    for (const value of [
      { owner, document },
      { owner, document: { ...document, kind: "generated" }, previewReplay },
      { owner, document, previewReplay: { ...previewReplay, path: "/private" } },
      {
        owner,
        document,
        previewReplay: { ...previewReplay, originalInputJson: "日".repeat(128 * 1024) },
      },
    ])
      expect(Result.isFailure(decode(value))).toBe(true);
    expect(
      Result.isFailure(
        Schema.decodeUnknownResult(VisualizationHostDocument)({ ...document, previewReplay }),
      ),
    ).toBe(true);
    expect(
      Result.isFailure(
        Schema.decodeUnknownResult(VisualizationHostPrepareInput)({
          ticket: "a".repeat(64),
          owner,
          document,
          previewReplay,
        }),
      ),
    ).toBe(true);
  });
});
